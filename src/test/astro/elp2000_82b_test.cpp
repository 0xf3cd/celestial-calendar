TEST(Elp2000, CreateContextExample47a) {
  // Meeus Example 47.a (p. 342): T = -0.077221081451 (1992 April 12, 0h TD); values as printed in the book.
  const auto ctx = create_context(-0.077221081451);
  ASSERT_NEAR(ctx.Lp.as<DEG>(), 134.290182, 5e-7);
  ASSERT_NEAR(ctx.D.as<DEG>(),  113.842304, 5e-7);
  ASSERT_NEAR(ctx.M.as<DEG>(),   97.643514, 5e-7);
  ASSERT_NEAR(ctx.Mp.as<DEG>(),   5.150833, 5e-7);
  ASSERT_NEAR(ctx.F.as<DEG>(),  219.889721, 5e-7);
  ASSERT_NEAR(ctx.A1.as<DEG>(),     109.57, 5e-3); // A1/A2/A3 are printed to 2 decimals in the book
  ASSERT_NEAR(ctx.A2.as<DEG>(),     123.78, 5e-3);
  ASSERT_NEAR(ctx.A3.as<DEG>(),     229.53, 5e-3);
  ASSERT_NEAR(ctx.E, 1.000194, 5e-7);
}

TEST(Elp2000, MeanArgumentsGolden) {
  // Regression for #65 (M's T^3 sign, Mp's T^4 denominator). Reference: Meeus (47.3)/(47.4)
  // evaluated with Python Decimal (40 digits), 2026-07-26. Tolerance 1e-8 deg: ~20x the double-rounding
  // floor (~5e-10 at jc=30), while the pre-fix code deviates >= 2.2e-6 on every sample below.
  const std::unordered_map<double, std::pair<double, double>> dataset {
    //jc                   M expected            Mp expected
    { -30.0, {  25.881039709187423, 296.363054283952616 } },
    { -10.0, {   7.010799367006942, 307.147454274621651 } },
    {  -3.0, {   0.376852997509187, 258.439159614270576 } },
    {   3.0, { 354.678600602490813,  11.644967374310175 } },
    {  10.0, { 348.016699032993058, 324.526259090903090 } },
    {  30.0, { 328.900698690812577, 349.188144323551462 } },
  };

  for (const auto& [jc, expected] : dataset) {
    const auto& [M, Mp] = expected;
    const auto ctx = create_context(jc);
    ASSERT_NEAR(ctx.M.as<DEG>(), M, 1e-8);
    ASSERT_NEAR(ctx.Mp.as<DEG>(), Mp, 1e-8);
  }
}


