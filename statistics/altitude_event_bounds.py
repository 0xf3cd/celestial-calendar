"""Derive selected altitude-event certificates from C++ sources and emit their runtime table.

The derivation assumes the stated elementary-function, integer-power and remainder
bounds. Its selected regions do not cover every admitted query; unavailable runtime
certificates cause numerical failure.
"""

import argparse
import copy
import datetime
import hashlib
import json
import math
import re
import sys
from fractions import Fraction as F
from pathlib import Path


HEADER_PATH = "src/astro/altitude_event_bounds.hpp"
TARGETS = ("sun", "moon", "mercury", "venus", "mars", "jupiter", "saturn", "uranus", "neptune", "pluto")
BANNER = """/*
 * CelestialCalendar:
 *   A C++23-style library that performs astronomical calculations and date conversions between
 *   Gregorian and Chinese Lunar calendars.
 *
 * Copyright (C) 2026 Ningqi Wang (0xf3cd)
 * Email: nq.maigre@gmail.com
 * Repo : https://github.com/0xf3cd/celestial-calendar
 *
 * SPDX-License-Identifier: MIT
 */

"""


def emit(near: dict, records: list, refraction: dict) -> tuple[str, dict]:
  """Emit directed bounds and return the exact clock/source relations encoded in the header."""
  from altitude_bounds.certificate_encoding import decode
  from altitude_bounds.clock_branch_majorants import branch_records, join_jumps
  from altitude_bounds.floating_operation_bounds import FloatingBound as B
  from altitude_bounds.poisson_majorants import DEGREE_RAD_UPPER, stored
  from altitude_bounds.rational_intervals import Interval as I
  from altitude_bounds.rounded_light_time_reach import outward_binary64
  from altitude_bounds.source_reading import serial

  if tuple(row["target"] for row in near["records"]) != TARGETS:
    raise ValueError("Near certificates must contain all ten physical targets in wire order")
  for row in near["records"]:
    for kind in ("ordinary", "collar"):
      values, codes = row[kind]["values"], row[kind]["codes"]
      if len(values) != 10 or len(codes) != 10:
        raise ValueError("An altitude packet must contain ten fields")
      for index, (value, code) in enumerate(zip(values, codes, strict=True)):
        if decode(code) > F(value) if index == 5 else decode(code) < F(value):
          raise ArithmeticError("An altitude packet rounded inward")

  constants = tuple(map(F, near["constants_exact"]))
  clock = copy.deepcopy(near["clock"])
  left, right = map(F, clock["tt_interval"])
  radius = max(abs(left - 2451545), abs(right - 2451545))
  delta = max(row["delta_t_year_derivatives"][0] for row in branch_records()[4:])
  d = radius + delta / 86400
  rate = DEGREE_RAD_UPPER * (
    stored("360.98564736629") + 2 * stored("0.000387933") * d / 36525**2 + 3 * d * d / (38710000 * 36525**3)
  )
  jumps = {row["year"]: row for row in join_jumps(branch_records())}
  for join in clock["model_joins"]:
    jump = jumps[F(join["year"])]
    join["residual_jump_upper"] = (
      2 * rate * max(abs(jump["jump_lower_seconds"]), abs(jump["jump_upper_seconds"])) / 86400
    )
  common = {
    "CLOCK_START": left,
    "CLOCK_END": right,
    "ROTATION_FIRST": F(clock["rotation"][1]),
    "ROTATION_SECOND": F(clock["rotation"][2]),
    "EARTH_RADIUS_AU": constants[0] / constants[2],
    "NORMAL_UPPER": 1 / I.enclose(constants[1]).sqrt().lo,
    "LATITUDE_TRIG_ERROR": B(F(90)).degrees_to_radians().sine_or_cosine().error,
    "YEAR_PAD_DAYS": 366 * F(clock["year_error_upper"]),
    "PLUTO_START": F(near["proofs"]["pluto"]["observation_interval"][0]),
    "PLUTO_END": F(near["proofs"]["pluto"]["observation_interval"][1]),
  }

  lines = [
    BANNER + "#pragma once",
    "",
    "#include <array>",
    "#include <cstddef>",
    "#include <cstdint>",
    "",
    "namespace astro::detail::altitude_bounds {",
    "",
    "// Generated by statistics/altitude_event_bounds.py from C++ sources.",
    "/** @brief D1/D2, R0/R1/R2/Rmin, residual c/h and q-magnitude c/h; TT days, AU and km. */",
    "using Packet = std::array<int8_t, 10>;",
    "",
    "/** @brief Closed TT collar and upper bound on its dimensionless clock-model jumps. */",
    "struct ClockJoin {",
    "  double before;",
    "  double after;",
    "  double jump;",
    "};",
    "",
    "/** @brief Smooth TT quarter with rotation bounds in radians per TT day and TT day squared. */",
    "struct LocalClock {",
    "  double start;",
    "  double end;",
    "  double first;",
    "  double second;",
    "};",
    "",
    "/** @brief Physical-target packet indexed into its complete local clock quarter. */",
    "struct LocalSource {",
    "  uint32_t target;",
    "  std::size_t clock;",
    "  Packet packet;",
    "};",
    "",
    "inline constexpr std::array<Packet, 10> RECORDS {{",
  ]
  for row in near["records"]:
    lines.append("  Packet { " + ", ".join(map(str, row["ordinary"]["codes"])) + " }, // " + row["target"])
  lines.extend(["}};", "", "inline constexpr std::array<std::array<int8_t, 2>, 10> COLLAR_ERRORS {{"])
  for row in near["records"]:
    if (
      row["ordinary"]["codes"][:6] != row["collar"]["codes"][:6]
      or row["ordinary"]["codes"][8:] != row["collar"]["codes"][8:]
    ):
      raise ArithmeticError("Clock choice changed a source or q-magnitude field")
    lines.append("  { " + ", ".join(map(str, row["collar"]["codes"][6:8])) + " },")
  lines.extend(["}};", ""])
  for name, value in common.items():
    lines.append("inline constexpr double " + name + " = " + float(outward_binary64(value, True)).hex() + ";")
  lines.extend(["", "inline constexpr std::array<ClockJoin, " + str(len(clock["model_joins"])) + "> MODEL_JOINS {{"])
  for row in clock["model_joins"]:
    lines.append(
      "  { .before = "
      + float(F(row["before"])).hex()
      + ", .after = "
      + float(F(row["after"])).hex()
      + ", .jump = "
      + float(outward_binary64(row["residual_jump_upper"], True)).hex()
      + " },"
    )
  lines.extend(["}};", ""])

  clocks, packets = [], []
  for row in records:
    interval = tuple(map(F, row["interval"]))
    if interval[1] - interval[0] != F(1, 4) or (4 * (interval[0] - 2451545)).denominator != 1:
      raise ValueError("A local runtime certificate must cover a complete canonical quarter")
    if len(row["codes"]) != 10 or row["target"] not in (4, 5, 6):
      raise ValueError("A local packet has an unsupported target or field count")
    for index, (value, code) in enumerate(zip(row["fields"], row["codes"], strict=True)):
      if decode(code) > F(value) if index == 5 else decode(code) < F(value):
        raise ArithmeticError("A local packet rounded inward")
    key = (*row["interval"], *row["rotation"])
    if key not in clocks:
      clocks.append(key)
    packets.append((row["target"], clocks.index(key), row["codes"]))
  lines.append("inline constexpr std::array<LocalClock, " + str(len(clocks)) + "> LOCAL_CLOCKS {{")
  for row in clocks:
    lines.append(
      "  { "
      + ", ".join(
        "." + name + " = " + float(outward_binary64(F(value), True)).hex()
        for name, value in zip(("start", "end", "first", "second"), row, strict=True)
      )
      + " },"
    )
  lines.extend(["}};", "", "inline constexpr std::array<LocalSource, " + str(len(packets)) + "> LOCAL_SOURCES {{"])
  for target, index, codes in packets:
    lines.append(
      "  { .target = "
      + str(target)
      + ", .clock = "
      + str(index)
      + ", .packet = Packet { "
      + ", ".join(map(str, codes))
      + " } },"
    )
  lines.extend(
    [
      "}};",
      "",
      "/** @brief Degree-valued map/residual error uppers and a dimensionless map-slope lower. */",
      "struct RefractionCertificate {",
      "  double map_error;",
      "  double residual_error;",
      "  double slope_lower;",
      "};",
      "",
      "// Bennett, then Saemundsson; weather support is T [-90, 60] C and P [300, 1100] hPa.",
      "inline constexpr std::array<RefractionCertificate, 2> REFRACTION {{",
    ]
  )
  certificates = refraction["certificates"]
  if tuple(row["model"] for row in certificates) != ("bennett", "saemundsson"):
    raise ValueError("Refraction certificates must match the source model order")
  for row in certificates:
    if not 0 < F(row["map_error"]) <= F(row["residual_error"]) or not 0 < F(row["slope_lower"]) <= 1:
      raise ValueError("A refraction certificate has invalid errors or slope")
    fields = ("map_error", "residual_error", "slope_lower")
    for field in fields:
      if outward_binary64(F(row[field]), True) != F(row[field]):
        raise ValueError("A refraction runtime field is not exact binary64")
    lines.append("  { " + ", ".join("." + field + " = " + float(F(row[field])).hex() for field in fields) + " },")
  lines.extend(["}};", "", "} // namespace astro::detail::altitude_bounds", ""])
  return "\n".join(lines), {
    "common": serial(common),
    "clock": serial(clock),
    "local_clocks": clocks,
    "local_packets": packets,
    "refraction_certificates": serial(certificates),
  }


def derive(root: Path, progress) -> tuple[dict, dict, dict]:
  """Recompute near tiers and explicit far rectangles from their current C++ coefficient sources."""
  from altitude_bounds import coefficient_reader as reader
  from altitude_bounds.affine_observer_error import affine_observer_error
  from altitude_bounds.certificate_encoding import decode, encode
  from altitude_bounds.floating_operation_bounds import FloatingBound as B
  from altitude_bounds.global_vsop_certificate import whole_tier_certificate
  from altitude_bounds.global_vsop_geometry import geometry_on_retardation_band
  from altitude_bounds.local_packets import derive as packets_for
  from altitude_bounds.local_rectangle import compose_rectangle
  from altitude_bounds.local_vector_separation import raw_cartesian_enclosure
  from altitude_bounds.ordinary_clock_tiers import ordinary_clock_tiers
  from altitude_bounds.other_body_tiers import other_body_tier
  from altitude_bounds.refraction_value_error import derive as refraction_for
  from altitude_bounds.source_c2_records import derive_vsop_record
  from altitude_bounds.source_reading import correction_expressions, serial, stored_constant, verify_mirrored_operations

  source_names = (
    "earth.hpp",
    "delta_t.hpp",
    "planet.hpp",
    "coord_transform.hpp",
    "observer.hpp",
    "toolbox.hpp",
    "pluto.hpp",
    "earth/precession.hpp",
    "earth/refraction.hpp",
    "vsop87d/defines.hpp",
    "julian_day.hpp",
    "sun.hpp",
    "moon.hpp",
  )
  text = {name: (root / "src/astro" / name).read_text() for name in source_names}
  verify_mirrored_operations(text)
  refraction = refraction_for(text["earth/refraction.hpp"], text["toolbox.hpp"])
  environment = {}
  for name in ("WGS84_EQUATORIAL_RADIUS_KM", "WGS84_INVERSE_FLATTENING", "WGS84_POLAR_RATIO_SQUARED"):
    environment[name] = stored_constant(text["observer.hpp"], name, environment)
  constants = (
    F(environment["WGS84_EQUATORIAL_RADIUS_KM"]),
    F(environment["WGS84_POLAR_RATIO_SQUARED"]),
    F(stored_constant(text["toolbox.hpp"], "AU_KM_SCALE", {})),
  )
  expressions = correction_expressions(text["planet.hpp"], text["coord_transform.hpp"])
  precession = re.sub(r"/\*.*?\*/|//[^\n]*", " ", text["earth/precession.hpp"], flags=re.DOTALL)
  tables, near_raw, far_raw, proofs = {}, {}, {}, {}
  for name in reader.PLANETS:
    source = root / "src/astro/vsop87d" / (name + "_coeff.hpp")
    tables[name] = reader.read_coefficients(source)
    near_raw[name] = derive_vsop_record(name, source, tables[name], F(21, 100))
    if name in ("earth", "mars", "jupiter", "saturn"):
      far_raw[name] = derive_vsop_record(name, source, tables[name], F(31))
    progress("raw", name)
  for name in reader.PLANETS:
    if name != "earth":
      geometry = geometry_on_retardation_band(near_raw[name], near_raw["earth"], tables[name], tables["earth"], F(1, 5))
      proofs[name] = whole_tier_certificate(
        near_raw[name], near_raw["earth"], geometry, precession, text["earth.hpp"], expressions
      )
      progress("near_value", name)
  left, right = F(2451545) - F(1, 5) * 365250, F(2451545) + F(1, 5) * 365250
  pluto = (
    F(stored_constant(text["pluto.hpp"], "APPARENT_START_JDE_TT", {})),
    F(math.nextafter(stored_constant(text["pluto.hpp"], "APPARENT_END_JDE_TT", {}), -math.inf)),
  )
  for name in ("sun", "moon", "pluto"):
    proofs[name] = other_body_tier(
      name,
      root,
      *(pluto if name == "pluto" else (left, right)),
      near_raw["earth"],
      tables["earth"],
      expressions,
      constants,
    )
    progress("near_value", name)
  clock = ordinary_clock_tiers(left, right, text["earth.hpp"], text["delta_t.hpp"])
  near_records = []
  for name in TARGETS:
    proof = proofs[name]
    fields = []
    for theta in (clock["ordinary_sidereal_degree_error"], clock["collar_sidereal_degree_error"]):
      affine = affine_observer_error(
        B(F(90)),
        proof["equatorial"]["stored_angle_direction_error"],
        theta,
        proof["distance_value"],
        F(proof["geometry"]["radial_lower_au"]),
        constants,
      )
      values = (
        *proof["apparent"]["equatorial_direction_norm"][1:3],
        *proof["distance_derivatives_au"][:3],
        F(proof["geometry"]["radial_lower_au"]),
        affine["residual"].error.constant,
        affine["residual"].error.height,
        affine["q"].magnitude.constant,
        affine["q"].magnitude.height,
      )
      codes = tuple(encode(value, index != 5) for index, value in enumerate(values))
      for index, (value, code) in enumerate(zip(values, codes, strict=True)):
        if decode(code) > value if index == 5 else decode(code) < value:
          raise ArithmeticError("A source packet rounded inward")
      fields.append({"values": values, "codes": codes})
    near_records.append({"target": name, "ordinary": fields[0], "collar": fields[1]})
  near = {
    "constants_exact": serial(constants),
    "raw": near_raw,
    "proofs": serial(proofs),
    "clock": serial(clock),
    "records": serial(near_records),
  }

  centres, rectangle_inputs, far_results = {}, [], []
  selections = [
    (name, centre, F(1, 8))
    for centre in (F("10000000.625"), F("13689000.625"))
    for name in ("mars", "jupiter", "saturn")
  ]
  selections.extend(("saturn", centre, F(1, 16)) for centre in (F("13689000.5625"), F("13689000.6875")))
  sites = tuple(tuple(map(F, site)) for site in ((0, 0, 0), (30, -77, 0), (90, 77, 0), (-90, -123, -1)))
  for name, centre, half in selections:
    vectors = {}
    for role, body in (("earth", "earth"), ("target", name)):
      key = body, centre
      if key not in centres:
        centres[key] = raw_cartesian_enclosure(tables[body], centre)
        progress("far_source_centre", body + "/" + str(centre))
      vectors[role] = centres[key]
    point = tuple(target - earth for target, earth in zip(vectors["target"], vectors["earth"], strict=True))
    row = {
      "planet": name,
      "centre_jde_tt": str(centre),
      "half_width_days": str(half),
      "source_centre_intervals_exact": {
        role: [[str(x.lo), str(x.hi)] for x in vector] for role, vector in vectors.items()
      },
      "centre_geocentric_intervals_exact": [[str(x.lo), str(x.hi)] for x in point],
    }
    rectangle_inputs.append(row)
    far_results.append(
      compose_rectangle(far_raw, row, precession, text["earth.hpp"], text["delta_t.hpp"], expressions, constants, sites)
    )
    progress("far_bounds", name + "/" + str(centre))
  records, exclusions = packets_for({"results": far_results}, text["earth.hpp"], constants)
  far = {
    "raw": far_raw,
    "inputs": rectangle_inputs,
    "results": far_results,
    "records": serial(records),
    "excluded": exclusions,
    "distinct_source_centres": len(centres),
  }
  return near, far, serial(refraction)


def main() -> None:
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
  parser.add_argument(
    "--output", type=Path, required=True, help="New output directory for the header and derivation record"
  )
  options = parser.parse_args()
  root, output = options.root.resolve(), options.output.resolve()
  output.mkdir(parents=True, exist_ok=False)
  library = Path(__file__).resolve().parent / "altitude_bounds"
  entry = Path(__file__).resolve()
  reads = set()
  sys.dont_write_bytecode = True
  sys.pycache_prefix = str(output / ".bytecode")

  def audit(event, args):
    if event != "open" or not isinstance(args[0], (str, bytes)):
      return
    path = Path(args[0].decode() if isinstance(args[0], bytes) else args[0]).resolve()
    mode, flags = args[1:3]
    writing = isinstance(mode, str) and any(letter in mode for letter in "wax+")
    writing = writing or bool(flags & 3)
    if writing:
      if not path.is_relative_to(output):
        raise PermissionError("Generator write escaped its output directory")
      return
    source = path.is_relative_to(root / "src/astro") and path.suffix == ".hpp"
    mathematical = (path.is_relative_to(library) or path == entry) and path.suffix == ".py"
    standard = path.is_relative_to(Path(sys.base_prefix) / "lib") and path.suffix in (".py", ".pyc", ".so")
    if not (source or mathematical or standard):
      raise PermissionError("Generator read is not a C++ source, mathematical module or Python runtime")
    reads.add(path)

  sys.addaudithook(audit)
  with (output / "progress.jsonl").open("x") as log:

    def progress(stage, name):
      log.write(json.dumps({"stage": stage, "name": name}) + "\n")
      log.flush()
      print(stage, name, flush=True)

    near, far, refraction = derive(root, progress)
  header, runtime = emit(near, far["records"], refraction)
  with (output / Path(HEADER_PATH).name).open("x") as stream:
    stream.write(header)
  sources = sorted(path for path in reads if path.is_relative_to(root / "src/astro"))
  modules = sorted({entry} | {path for path in reads if path.is_relative_to(library)})
  module_names = {path: str(path.relative_to(entry.parent)) for path in modules}
  record = {
    "schema": 1,
    "at": datetime.datetime.now(datetime.UTC).isoformat(),
    "near": near,
    "far": far,
    "runtime": runtime,
    "refraction": refraction,
    "generated_sha256": {HEADER_PATH: hashlib.sha256(header.encode()).hexdigest()},
    "source_sha256": {str(path.relative_to(root)): hashlib.sha256(path.read_bytes()).hexdigest() for path in sources},
    "module_sha256": {module_names[path]: hashlib.sha256(path.read_bytes()).hexdigest() for path in modules},
    "audited_reads": {
      "source": [str(path.relative_to(root)) for path in sources],
      "modules": [module_names[path] for path in modules],
    },
    "premises": (
      "Conditional elementary-function, integer-power and exact-remainder bounds. "
      "Selected source regions only; unavailable certificates fail numerically."
    ),
  }
  with (output / "derivation.json").open("x") as stream:
    stream.write(json.dumps(record, indent=2) + "\n")
  print("ALTITUDE_BOUND_DERIVATION complete source-derived near and local certificates")


if __name__ == "__main__":
  main()
