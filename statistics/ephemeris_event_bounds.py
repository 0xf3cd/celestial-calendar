"""Check source identities and emit the exact event-bound records as C++.

This checks transcription and directed binary64 serialization, not the
coefficient-majorant derivation or a deployment's elementary functions.
"""

import argparse
import hashlib
import json
import math
import runpy

from fractions import Fraction
from pathlib import Path


TARGETS = (
  "SUN",
  "MOON",
  "MERCURY",
  "VENUS",
  "MARS",
  "JUPITER",
  "SATURN",
  "URANUS",
  "NEPTUNE",
  "PLUTO",
  "MEAN_ASCENDING",
  "MEAN_DESCENDING",
  "TRUE_ASCENDING",
  "TRUE_DESCENDING",
)
RECORD_PATH = "src/test/provenance/ephemeris-events/BOUND_RECORDS.json"
HEADER_PATH = "src/astro/ephemeris_event_bounds.hpp"
SOURCE_DIGEST = runpy.run_path(str(Path(__file__).resolve().parents[1] / "automation/source_digest.py"))
SOURCE_PATHS = (
  "src/astro/ephemeris.hpp",
  "src/astro/lunar_node.hpp",
  "src/astro/moon.hpp",
  "src/astro/elp2000_82b.hpp",
  "src/astro/planet.hpp",
  "src/astro/pluto.hpp",
  "src/astro/earth.hpp",
  "src/astro/julian_day.hpp",
  "src/astro/toolbox.hpp",
  "src/astro/coord_transform.hpp",
  "src/astro/earth/precession.hpp",
  "src/astro/vsop87d/defines.hpp",
  "src/astro/vsop87d/earth_coeff.hpp",
  "src/astro/vsop87d/mercury_coeff.hpp",
  "src/astro/vsop87d/venus_coeff.hpp",
  "src/astro/vsop87d/mars_coeff.hpp",
  "src/astro/vsop87d/jupiter_coeff.hpp",
  "src/astro/vsop87d/saturn_coeff.hpp",
  "src/astro/vsop87d/uranus_coeff.hpp",
  "src/astro/vsop87d/neptune_coeff.hpp",
  "src/astro/sun.hpp",
)


def source_identity(root: Path) -> dict:
  """Identify complete numerical headers without depending on their comments or layout."""
  hashes = {}
  for name in SOURCE_PATHS:
    try:
      hashes[name] = SOURCE_DIGEST["cpp_token_digest"]((root / name).read_text(encoding="utf-8"))
    except ValueError as error:
      raise ValueError(f"Cannot identify event-bound source {name}: {error}") from error
  return {
    "algorithm": SOURCE_DIGEST["CPP_TOKEN_ALGORITHM"],
    "version": SOURCE_DIGEST["CPP_TOKEN_VERSION"],
    "sha256": hashes,
  }


def validate_source_identity(record: dict) -> None:
  identity = record.get("source_identity", {})
  if not isinstance(identity, dict):
    raise ValueError("Unsupported event-bound source identity")
  SOURCE_DIGEST["validate_cpp_token_algorithm"](identity.get("algorithm"), identity.get("version"))
  hashes = identity.get("sha256")
  if (
    set(identity) != {"algorithm", "version", "sha256"}
    or not isinstance(hashes, dict)
    or set(hashes) != set(SOURCE_PATHS)
    or any(
      not isinstance(value, str) or len(value) != 64 or set(value) - set("0123456789abcdef")
      for value in hashes.values()
    )
  ):
    raise ValueError("Unsupported event-bound source coverage")


def directed(record: dict, lower: bool = False) -> str:
  """Require the literal to enclose its exact rational in the intended signed direction."""
  value = float.fromhex(record["hex"])
  if not math.isfinite(value):
    raise ValueError("Non-finite event bound")
  exact = Fraction(record["exact"])
  wrong_direction = Fraction(value) > exact if lower else Fraction(value) < exact
  if wrong_direction:
    raise ValueError("Event bound points in the wrong rounding direction")
  return record["hex"]


def emit(record: dict) -> str:
  """Render all fourteen records in their fixed Target order without changing mathematical values."""
  if (
    record["schema"] != 2
    or tuple(record["target_order"]) != TARGETS
    or record["epsilon_hex"] != "0x1.0000000000000p-48"
  ):
    raise ValueError("Unsupported event-bound schema, target order or elementary-function premise")
  validate_source_identity(record)
  lines = [
    "/*",
    " * CelestialCalendar:",
    " *   A C++23-style library that performs astronomical calculations and date conversions between",
    " *   Gregorian and Chinese Lunar calendars.",
    " *",
    " * Copyright (C) 2026 Ningqi Wang (0xf3cd)",
    " * Email: nq.maigre@gmail.com",
    " * Repo : https://github.com/0xf3cd/celestial-calendar",
    " *",
    " * SPDX-License-Identifier: MIT",
    " */",
    "",
    "#pragma once",
    "",
    "#include <array>",
    "#include <optional>",
    "",
    '#include "ephemeris.hpp"',
    '#include "event_search.hpp"',
    "",
    "namespace astro::ephemeris::detail {",
    "",
    "// Generated by statistics/ephemeris_event_bounds.py",
    "// from src/test/provenance/ephemeris-events/BOUND_RECORDS.json.",
    "/** @brief Source-model derivative and evaluation allowances under the event-search floating-point contract. */",
    "struct EventBounds {",
    "  astro::detail::event_search::TrajectoryBounds trajectory;",
    "  double position_error_deg;",
    "  double rate_error_deg_per_day;",
    "  std::optional<double> minimum_rate;",
    "  std::optional<double> maximum_rate;",
    "};",
    "",
    "// Indexed by Target; all floating literals enclose the exact offline bound in its required direction.",
  ]
  for name in ("EVENT_BOUNDS_WIDE", "EVENT_BOUNDS_CENTURY"):
    table = record["tables"][name]
    if set(table) != set(TARGETS):
      raise ValueError("Incomplete event-bound table")
    lines.append(f"inline constexpr std::array<EventBounds, {len(TARGETS)}> {name} {{{{")
    for target in TARGETS:
      item = table[target]

      def value(field: str, item: dict = item) -> str:
        if Fraction(item[field]["exact"]) < 0:
          raise ValueError("Negative magnitude/error bound")
        return directed(item[field])

      def optional(field: str, item: dict = item) -> str:
        if item[field] is None:
          return "std::nullopt"
        return "std::optional<double> { " + directed(item[field], lower=field == "signed_rate_lower") + " }"

      lines += [
        f"  // {target}",
        "  {",
        "    .trajectory = {",
        "      .longitude = { .first_derivative = "
        + value("position_first_derivative")
        + ", .second_derivative = "
        + value("position_second_derivative")
        + " },",
        "      .rate = { .first_derivative = "
        + value("rate_first_derivative")
        + ", .second_derivative = "
        + value("rate_second_derivative")
        + " },",
        "      .third_derivative = " + value("position_third_derivative") + ",",
        "      .rate_remainder = " + value("rate_to_position_derivative_remainder") + ",",
        "    },",
        "    .position_error_deg = " + value("position_error") + ",",
        "    .rate_error_deg_per_day = " + value("rate_error") + ",",
        "    .minimum_rate = " + optional("signed_rate_lower") + ",",
        "    .maximum_rate = " + optional("signed_rate_upper") + ",",
        "  },",
      ]
    lines += ["}};", ""]
  lines += ["} // namespace astro::ephemeris::detail", ""]
  return "\n".join(lines)


def check_sources(record: dict, actual: dict) -> None:
  """Invalidate bound evidence when a pinned numerical source changes."""
  validate_source_identity(record)
  if record["source_identity"] != actual:
    raise ValueError("Event-bound source identity changed; recheck the affected numerical evidence")


def check_math_references(record: dict, generator_sha256: str, header_sha256: str) -> None:
  """Reject changes to the frozen math witnesses or their collector without importing the optional oracle."""
  if record["generator_sha256"] != generator_sha256 or record["header_sha256"] != header_sha256:
    raise ValueError("Event math-reference identity changed; recheck the affected oracle evidence")


def main() -> None:
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--check", action="store_true", help="Check the source pins and generated header")
  args = parser.parse_args()
  root = Path(__file__).resolve().parents[1]
  record = json.loads((root / RECORD_PATH).read_text(encoding="utf-8"))
  rendered = emit(record)
  if args.check:
    check_sources(record, source_identity(root))
    if rendered != (root / HEADER_PATH).read_text(encoding="utf-8"):
      raise ValueError("C++ event bounds do not match the exact records")
    references = (root / RECORD_PATH).parent
    check_math_references(
      json.loads((references / "LIBM_REFERENCE_PINS.json").read_text(encoding="utf-8")),
      hashlib.sha256((root / "statistics/ephemeris_event_math_reference.py").read_bytes()).hexdigest(),
      hashlib.sha256((references / "libm_reference.hpp").read_bytes()).hexdigest(),
    )
    print("Event-bound source pins, directed C++ literals and math-reference identities match")
  else:
    print(rendered, end="")


if __name__ == "__main__":
  main()
